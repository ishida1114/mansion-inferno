export function handleEvent2F(targetCode) {
    switch(targetCode) {
        case 2:
            alert("【客室の扉】固く閉ざされている。ドアノブを回してもビクともしない…");
            break;
        case 4:
            // 1階へ下りるアクションを返す
            return { type: "changeFloor", targetFloor: 1 };
        default:
            break;
    }
    return null;
}